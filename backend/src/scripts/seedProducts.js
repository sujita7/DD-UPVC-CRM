export async function resetToExact34() {
  await connectDB();
  console.log(`\n🌱 Resetting MySQL products table to EXACTLY 34 products and 12 categories...`);

  // Delete all existing products to ensure clean 34 count
  await Product.deleteMany({});
  console.log("Deleted old products.");

  let created = 0;
  for (const item of exact34Products) {
    const prod = new Product(item);
    await prod.save();
    created++;
  }

  console.log(`✅ Success: Exactly ${created} products seeded into MySQL.`);
}

if (process.argv[1]?.endsWith("seedProducts.js")) {
  resetToExact34()
    .then(async () => {
      await disconnectDB();
      process.exit(0);
    })
    .catch((err) => {
      console.error("Seeding failed:", err);
      process.exit(1);
    });
}
